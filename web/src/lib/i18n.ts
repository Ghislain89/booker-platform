const dictionaries: Record<Language, Record<MessageKey, string>> = { en, nl };

export const LOCALES: Record<Language, string> = { en: "en-US", nl: "nl-NL" };

export type Translate = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function makeTranslator(language: Language): Translate {
  const dictionary = dictionaries[language];
  return (key, values) =>
    dictionary[key].replace(/\{(\w+)\}/g, (match, name) =>
      values && name in values ? String(values[name]) : match,
    );
}
